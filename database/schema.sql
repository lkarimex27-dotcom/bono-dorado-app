
CREATE TABLE IF NOT EXISTS beneficiaries (
  id BIGSERIAL PRIMARY KEY,
  item INTEGER,
  nombres TEXT,
  apellidos TEXT,
  documento TEXT NOT NULL UNIQUE,
  pasaporte TEXT,
  telefono TEXT,
  correo TEXT,
  telegram TEXT,
  comprobante_hash TEXT,
  ciudad_residencia TEXT,
  aeropuerto_cercano TEXT,
  pais_residencia TEXT,
  pasaporte_url TEXT,
  cuenta_bancaria TEXT,
  banco TEXT,
  tipo_cuenta TEXT,
  cantidad_bonos TEXT,
  valor_consignado TEXT,
  lider TEXT,
  no_tiene_cuenta_o_no_puede_recibir BOOLEAN,
  tercero_nombres TEXT,
  tercero_apellidos TEXT,
  tercero_documento TEXT,
  tercero_numero_cuenta TEXT,
  tercero_banco TEXT,
  autorizacion_nombre_archivo TEXT,
  autorizacion_mime_type TEXT,
  autorizacion_archivo BYTEA,
  pasaporte_nombre_archivo TEXT,
  pasaporte_mime_type TEXT,
  pasaporte_archivo BYTEA,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_beneficiaries_pasaporte ON beneficiaries (pasaporte);
